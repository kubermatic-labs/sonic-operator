func TestACLRuntimeRequiresAppliedObjectChain(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ name, vid string }{
		{"table", aclTestTable}, {"entry", aclTestEntryWeb}, {"counter", aclTestCounterWeb},
		{"port", aclTestPort}, {"group", aclTestGroup}, {"group member", aclTestMember},
	} {
		for _, mode := range []string{"missing translation", "null RID", "invalid RID", "overflow RID", "aliased RID", "wrong VID type", "extension VID type"} {
			t.Run(tc.name+"/"+mode, func(t *testing.T) {
				db := aclNativeFixture()
				aclFixtureBind(db)
				ids := db["ASIC_DB"]["VIDTORID"]
				switch mode {
				case "missing translation":
					delete(ids, tc.vid)
				case "null RID":
					ids[tc.vid] = "oid:0x0"
				case "invalid RID":
					ids[tc.vid] = "pending"
				case "overflow RID":
					ids[tc.vid] = "oid:0x10000000000000000"
				case "aliased RID":
					ids["oid:0x1000000000099"] = ids[tc.vid]
				case "wrong VID type":
					aclFixtureReplaceOID(db, tc.vid, "oid:0x3000000000099")
				case "extension VID type":
					// Same base type byte but the sairedis extension flag is set.
					aclFixtureReplaceOID(db, tc.vid, strings.Replace(tc.vid, "0000000000", "0080000000", 1))
				}
				p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
				if err != nil {
					t.Fatal(err)
				}
				read, scan := aclFixtureReaders(db)
				ok, raw, _ := aclRuntime(t.Context(), "EDGE", p.Desired, []string{"Ethernet0"}, read, scan)
				if ok {
					t.Fatalf("unapplied/wrong-type %s qualified: %s", tc.name, raw)
				}
			})
		}
	}
	t.Run("unbound requested records without translations", func(t *testing.T) {
		db := aclNativeFixture()
		delete(db["ASIC_DB"], "VIDTORID")
		read, scan := aclFixtureReaders(db)
		p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
		if err != nil {
			t.Fatal(err)
		}
		ok, raw, err := aclRuntime(t.Context(), "EDGE", p.Desired, nil, read, scan)
		if ok || err != nil {
			t.Fatalf("pending observation: %s %v", raw, err)
		}
	})
}

// Rewrite the entire fixture's references as well as keys so wrong-type tests
// remain fully correlated and fail specifically on the object's VID type.
func aclFixtureReplaceOID(db map[string]vlanChangeDB, old, replacement string) {
	for _, objects := range db {
		updated := vlanChangeDB{}
		for key, fields := range objects {
			out := map[string]string{}
			for field, value := range fields {
				out[strings.ReplaceAll(field, old, replacement)] = strings.ReplaceAll(value, old, replacement)
			}
			updated[strings.ReplaceAll(key, old, replacement)] = out
		}
		clear(objects)
		maps.Copy(objects, updated)
	}
}

func TestACLRuntimeLAGTranslation(t *testing.T) {
	t.Parallel()
	for _, mode := range []string{"applied", "missing translation", "wrong type"} {
		t.Run(mode, func(t *testing.T) {
			db := aclNativeFixture()
			aclFixtureBind(db)
			delete(db["ASIC_DB"], aclASIC+"PORT:"+aclTestPort)
			db["ASIC_DB"][aclASIC+"LAG:"+aclTestLAG] = map[string]string{"SAI_LAG_ATTR_INGRESS_ACL": aclTestGroup}
			db["ASIC_DB"]["VIDTORID"][aclTestLAG] = "oid:0x109"
			db["COUNTERS_DB"]["COUNTERS_LAG_NAME_MAP"] = map[string]string{"PortChannel1": aclTestLAG}
			db["STATE_DB"]["LAG_TABLE|PortChannel1"] = map[string]string{"state": "ok"}
			if mode == "missing translation" {
				delete(db["ASIC_DB"]["VIDTORID"], aclTestLAG)
			}
			if mode == "wrong type" {
				aclFixtureReplaceOID(db, aclTestLAG, "oid:0x1000000000071")
			}
			read, scan := aclFixtureReaders(db)
			p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
			if err != nil {
				t.Fatal(err)
			}
			ok, raw, err := aclRuntime(t.Context(), "EDGE", p.Desired, []string{"PortChannel1"}, read, scan)
			if ok != (mode == "applied") || (ok && err != nil) {
				t.Fatalf("LAG %s: %s %v", mode, raw, err)
			}
		})
	}
}

func TestACLRuntimeTranslationReadAndChurn(t *testing.T) {
	t.Parallel()
	for _, mode := range []string{"read error", "removed during observation", "replaced during observation"} {
		t.Run(mode, func(t *testing.T) {
			db := aclNativeFixture()
			read, scan := aclFixtureReaders(db)
			reads := 0
			wrapped := func(ctx context.Context, name, key string) (map[string]string, error) {
				if name == "ASIC_DB" && key == "VIDTORID" {
					reads++
					if mode == "read error" {
						return nil, errors.New("translation read denied")
					}
					if reads > 1 {
						if mode == "removed during observation" {
							delete(db["ASIC_DB"]["VIDTORID"], aclTestEntryWeb)
						} else {
							db["ASIC_DB"]["VIDTORID"][aclTestEntryWeb] = "oid:0x200"
						}
					}
				}
				return read(ctx, name, key)
			}
			p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
			if err != nil {
				t.Fatal(err)
			}
			ok, raw, err := aclRuntime(t.Context(), "EDGE", p.Desired, nil, wrapped, scan)
			if ok || ((err != nil) != (mode == "read error")) {
				t.Fatalf("translation failure hidden: %s %v", raw, err)
			}
		})
	}
}
