	db["ASIC_DB"][aclASIC+"PORT:"+aclTestPort]["SAI_PORT_ATTR_INGRESS_ACL"] = aclTestGroup
	db["ASIC_DB"][aclASIC+"ACL_TABLE_GROUP:"+aclTestGroup] = map[string]string{"SAI_ACL_TABLE_GROUP_ATTR_ACL_STAGE": "SAI_ACL_STAGE_INGRESS", "SAI_ACL_TABLE_GROUP_ATTR_TYPE": "SAI_ACL_TABLE_GROUP_TYPE_PARALLEL"}
	db["ASIC_DB"][aclASIC+"ACL_TABLE_GROUP_MEMBER:"+aclTestMember] = map[string]string{"SAI_ACL_TABLE_GROUP_MEMBER_ATTR_ACL_TABLE_GROUP_ID": aclTestGroup, "SAI_ACL_TABLE_GROUP_MEMBER_ATTR_ACL_TABLE_ID": aclTestTable}
	db["ASIC_DB"]["VIDTORID"][aclTestGroup] = "oid:0x107"
