func aclFixtureReaders(db map[string]vlanChangeDB) (aclReader, aclScanner) {
	read := func(ctx context.Context, name, key string) (map[string]string, error) {
		return maps.Clone(db[name][key]), ctx.Err()
	}
	scan := func(ctx context.Context, name, prefix string) (vlanChangeDB, error) {
		out := vlanChangeDB{}
		for key, fields := range db[name] {
			if strings.HasPrefix(key, prefix) {
				out[key] = maps.Clone(fields)
			}
		}
		return out, ctx.Err()
	}
	return read, scan
}

func TestACLRuntimeExactTargetCounters(t *testing.T) {
	t.Parallel()
	p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
	if err != nil {
		t.Fatal(err)
	}
	read, scan := aclFixtureReaders(aclNativeFixture())
	ok, raw, err := aclRuntime(t.Context(), "EDGE", p.Desired, nil, read, scan)
	if err != nil || !ok {
		t.Fatalf("%s %v", raw, err)
	}
	var observed aclObserved
	if err := json.Unmarshal(raw, &observed); err != nil {
		t.Fatal(err)
	}
	if observed.TableOID != aclTestTable || observed.AppliedRules != 2 || observed.ObservedEntries != 2 || observed.ObservedCounters != 2 || *observed.Rules["WEB"].Packets != ^uint64(0) || *observed.Rules["DEFAULT"].Packets != 0 {
		t.Fatalf("incorrect target observation %s", raw)
	}
}

func TestACLRuntimeRejectsIncompleteOrOpaqueEvidence(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name   string
		mutate func(map[string]vlanChangeDB)
	}{
		{"state pending", func(db map[string]vlanChangeDB) {
			db["STATE_DB"]["ACL_RULE_TABLE|EDGE|WEB"]["status"] = "Pending creation"
		}},
		{"missing map", func(db map[string]vlanChangeDB) { delete(db["COUNTERS_DB"]["ACL_COUNTER_RULE_MAP"], "EDGE:WEB") }},
		{"aliased counter", func(db map[string]vlanChangeDB) {
			db["COUNTERS_DB"]["ACL_COUNTER_RULE_MAP"]["OTHER:WEB"] = aclTestCounterWeb
		}},
		{"wrong table", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_COUNTER:"+aclTestCounterWeb]["SAI_ACL_COUNTER_ATTR_TABLE_ID"] = "oid:0x7000000000098"
		}},
		{"missing packets", func(db map[string]vlanChangeDB) {
			delete(db["COUNTERS_DB"]["COUNTERS:"+aclTestCounterWeb], "SAI_ACL_COUNTER_ATTR_PACKETS")
		}},
		{"counter overflow", func(db map[string]vlanChangeDB) {
			db["COUNTERS_DB"]["COUNTERS:"+aclTestCounterWeb]["SAI_ACL_COUNTER_ATTR_PACKETS"] = "18446744073709551616"
		}},
		{"extra entry", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_ENTRY:oid:0x8000000000098"] = maps.Clone(db["ASIC_DB"][aclASIC+"ACL_ENTRY:"+aclTestEntryWeb])
		}},
		{"extra counter", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_COUNTER:oid:0x9000000000098"] = maps.Clone(db["ASIC_DB"][aclASIC+"ACL_COUNTER:"+aclTestCounterWeb])
		}},
		{"opaque action", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_ENTRY:"+aclTestEntryWeb]["SAI_ACL_ENTRY_ATTR_ACTION_REDIRECT"] = "oid:0x1000000000042"
		}},
		{"wrong mask", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_ENTRY:"+aclTestEntryWeb]["SAI_ACL_ENTRY_ATTR_FIELD_SRC_IP"] = "192.0.2.0&mask:255.255.0.0"
		}},
		{"wrong action", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_ENTRY:"+aclTestEntryDefault]["SAI_ACL_ENTRY_ATTR_ACTION_PACKET_ACTION"] = "SAI_PACKET_ACTION_FORWARD"
		}},
		{"counter disabled", func(db map[string]vlanChangeDB) {
			db["ASIC_DB"][aclASIC+"ACL_COUNTER:"+aclTestCounterDefault]["SAI_ACL_COUNTER_ATTR_ENABLE_PACKET_COUNT"] = "false"
		}},
		{"unknown target map", func(db map[string]vlanChangeDB) {
			db["COUNTERS_DB"]["ACL_COUNTER_RULE_MAP"]["EDGE:UNKNOWN"] = "oid:0x9000000000099"
		}},
		{"bound table", aclFixtureBind},
	} {
		t.Run(tc.name, func(t *testing.T) {
			db := aclNativeFixture()
			tc.mutate(db)
			read, scan := aclFixtureReaders(db)
			p, err := planNetworkACLPolicy(nil, aclRequest("ACLPolicy", aclTestSpec))
			if err != nil {
				t.Fatal(err)
			}
			ok, raw, err := aclRuntime(t.Context(), "EDGE", p.Desired, nil, read, scan)
			if err != nil || ok {
				t.Fatalf("false readiness/error: %s %v", raw, err)
			}
		})
	}
}

